Test("Replace is one step and restores its selected occurrence", function()
    local page, editBox = Editor("one one")
    page:OpenSearch(true); page.FindBox:SetText("one")
    page:NavigateSearch(1)
    local first = page.SearchMatches[page.SearchIndex].First
    page.ReplaceBox:SetText("two"); page:ReplaceSearchMatch()
    Equal(editBox:GetText(), "one two")
    Equal(#page.EditorHistory.States, 2)
    page:UndoEditor(); Equal(editBox:GetText(), "one one")
    Equal(editBox.highlight[1], first)
    Equal(editBox.highlight[2], first + 3)
    Equal(#page.SearchMatches, 2)
    page:RedoEditor(); Equal(editBox:GetText(), "one two")
    Equal(#page.SearchMatches, 1)
end)

Test("Replace All is exactly one step with UTF-8 and empty replacements", function()
    local original = string.rep("😀 café\n", 200)
    local page, editBox = Editor(original)
    page:OpenSearch(true); page.FindBox:SetText("café")
    page.ReplaceBox:SetText(""); page:ReplaceAllSearchMatches()
    Equal(editBox:GetText(), string.rep("😀 \n", 200))
    Equal(#page.EditorHistory.States, 2)
    page:UndoEditor(); Equal(editBox:GetText(), original)
    page:RedoEditor(); Equal(editBox:GetText(), string.rep("😀 \n", 200))
    Equal(#page.EditorHistory.States, 2)
end)

Test("unchanged replacements and empty searches create no history", function()
    local page = Editor("one one")
    page:OpenSearch(true); page.FindBox:SetText("one")
    page.ReplaceBox:SetText("one")
    page:ReplaceSearchMatch(); page:ReplaceAllSearchMatches()
    page.FindBox:SetText(""); page:ReplaceAllSearchMatches()
    Equal(#page.EditorHistory.States, 1)
end)

Test("history retains 20 changes plus one baseline across Undo and Redo", function()
    local page, editBox = Editor()
    for i = 1, 25 do editBox:SetText("state" .. i) end
    Equal(#page.EditorHistory.States, 21)
    for _ = 1, 20 do page:UndoEditor() end
    Equal(editBox:GetText(), "state5")
    page:UndoEditor(); Equal(editBox:GetText(), "state5")
    for _ = 1, 20 do page:RedoEditor() end
    Equal(editBox:GetText(), "state25")
    page:RedoEditor(); Equal(editBox:GetText(), "state25")
    Equal(#page.EditorHistory.States, 21)
end)

Test("new edits discard the redo branch", function()
    local page, editBox = Editor()
    Paste(editBox, "one"); Paste(editBox, "two")
    page:UndoEditor(); Equal(editBox:GetText(), "one")
    Type(editBox, "new")
    page:RedoEditor(); Equal(editBox:GetText(), "onenew")
    page:UndoEditor(); Equal(editBox:GetText(), "one")
    page:UndoEditor(); Equal(editBox:GetText(), "")
end)

Test("editing after Undo to the oldest retained state discards all redo", function()
    local page, editBox = Editor()
    for i = 1, 25 do editBox:SetText(tostring(i)) end
    for _ = 1, 20 do page:UndoEditor() end
    Type(editBox, "X")
    page:RedoEditor(); Equal(editBox:GetText(), "5X")
    Equal(#page.EditorHistory.States, 2)
end)

Test("no-op updates and navigation preserve redo", function()
    local page, editBox = Editor()

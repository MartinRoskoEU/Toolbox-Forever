Test("Clear is undoable without replaying or restoring Console Output", function()
    local page, editBox = Editor("keep this")
    local outputClears = 0
    page.ClearOutput = function() outputClears = outputClears + 1 end
    page.ClearButton:Fire("OnClick")
    Equal(editBox:GetText(), "")
    Equal(outputClears, 1)
    page:UndoEditor(); Equal(editBox:GetText(), "keep this")
    page:RedoEditor(); Equal(editBox:GetText(), "")
    Equal(outputClears, 1)
end)

Test("a programmatic transaction batches multiple updates", function()
    local page, editBox = Editor("baseline")
    page:BeginEditorHistoryOperation()
    editBox:SetText("intermediate")
    editBox:SetText("final")
    editBox:SetCursorPosition(2)
    page:EndEditorHistoryOperation()
    Equal(#page.EditorHistory.States, 2)
    page:UndoEditor(); Equal(editBox:GetText(), "baseline")
    page:RedoEditor(); Equal(editBox:GetText(), "final")
    Equal(editBox:GetCursorPosition(), 2)
end)

Test("Undo and Redo preserve UTF-8 cursor byte boundaries", function()

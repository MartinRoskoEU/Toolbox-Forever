    Type(editBox, "漢é")
    page:UndoEditor(); Equal(editBox:GetText(), "ž😀")
    Equal(editBox:GetCursorPosition(), #"ž😀")
    page:RedoEditor(); Equal(editBox:GetText(), "ž😀漢é")
    Equal(editBox:GetCursorPosition(), #"ž😀漢é")
end)

Test("repeated Undo and Redo cycles preserve exact content and history size", function()
    local page, editBox = Editor("baseline\n")
    for i = 1, 20 do Paste(editBox, "line " .. i .. " 😀\n") end
    local final = editBox:GetText()
    for _ = 1, 10 do
        for _ = 1, 20 do page:UndoEditor() end
        Equal(editBox:GetText(), "baseline\n")
        for _ = 1, 20 do page:RedoEditor() end
        Equal(editBox:GetText(), final)
        Equal(#page.EditorHistory.States, 21)
    end
end)

Test("history survives page or window hide and show", function()
    local page, editBox = Editor()
    Type(editBox, "first")
    page.Page.Frame:Hide(); page.Page.Frame:Show()
    editBox:SetFocus(); Type(editBox, "second")
    page:UndoEditor(); Equal(editBox:GetText(), "first")
    page:UndoEditor(); Equal(editBox:GetText(), "")
end)

Test("reset history keeps the current text as the sole baseline", function()
    local page, editBox = Editor()
    Type(editBox, "keep this")
    page:ResetEditorHistory()
    page:UndoEditor(); page:RedoEditor()
    Equal(editBox:GetText(), "keep this")
    Equal(#page.EditorHistory.States, 1)
    local other = Editor()
    Equal(#other.EditorHistory.States, 1)
    Equal(other.EditorHistory == page.EditorHistory, false)
end)

Test("Find, Replace and page-level keyboard handling do not consume Undo", function()
    local page, editBox = Editor()
    Type(editBox, "keep")
    page:OpenSearch(true)
    support.SetModifiers(true, false, false)
    page.FindBox:Fire("OnKeyDown", "Z")
    page.ReplaceBox:Fire("OnKeyDown", "Y")
    page.FindBox:Fire("OnKeyDown", "Z")
    page.Page.Frame:Fire("OnKeyDown", "Z")
    support.SetModifiers(false, false, false)
    Equal(editBox:GetText(), "keep")
    Equal(page.EditorHistory.Index, 2)
    Equal(page.Page.Frame.propagate, true)
end)

Test("Undo and Redo preserve editor focus and scroll to the restored caret", function()
    local page, editBox = Editor("before\n")
    Type(editBox, "after")
    Shortcut(editBox, "Z")
    Equal(editBox:HasFocus(), true)
    Equal(page.InputEditor.scrolledCursor, #"before\n")
    Shortcut(editBox, "Y")
    Equal(editBox:HasFocus(), true)
    Equal(page.InputEditor.scrolledCursor, #"before\nafter")
end)

Test("the existing shortcut hint includes Find, Replace, Undo and Redo", function()
    local page = Editor()
    local hint = page.SearchHint:GetText()
    Equal(hint:find("Ctrl+F: Find", 1, true) ~= nil, true)
    Equal(hint:find("Ctrl+H: Find & Replace", 1, true) ~= nil, true)
    Equal(hint:find("Ctrl+Z: Undo", 1, true) ~= nil, true)
    Equal(hint:find("Ctrl+Y: Redo", 1, true) ~= nil, true)
end)


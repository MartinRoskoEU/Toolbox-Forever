end)

Test("paste is separate from surrounding typing", function()
    local page, editBox = Editor()
    Type(editBox, "a"); Paste(editBox, "b"); Type(editBox, "c")
    Equal(#page.EditorHistory.States, 4)
    page:UndoEditor(); Equal(editBox:GetText(), "ab")
    page:UndoEditor(); Equal(editBox:GetText(), "a")
    page:RedoEditor(); Equal(editBox:GetText(), "ab")
end)

Test("multiline UTF-8 paste is one operation even with multiple notifications", function()
    local page, editBox = Editor("start\n")
    local pasted = string.rep("local café = '😀'\n", 100)
    Paste(editBox, pasted, true)
    Equal(#page.EditorHistory.States, 2)
    page:UndoEditor(); Equal(editBox:GetText(), "start\n")
    page:RedoEditor(); Equal(editBox:GetText(), "start\n" .. pasted)
end)

Test("Shift+Insert paste is one operation", function()
    local page, editBox = Editor()
    support.SetModifiers(false, true, false)
    editBox:Fire("OnKeyDown", "INSERT")
    editBox:Insert("a"); editBox:Insert("b")
    editBox:Fire("OnKeyUp", "INSERT")
    support.SetModifiers(false, false, false)
    Equal(#page.EditorHistory.States, 2)
    page:UndoEditor(); Equal(editBox:GetText(), "")
end)

Test("cut is undoable and can restore an owned selection", function()
    local page, editBox = Editor("cut this")
    Shortcut(editBox, "A")
    editBox:HighlightText(0, #editBox:GetText())
    support.SetModifiers(true, false, false)
    editBox:Fire("OnKeyDown", "X"); editBox:Insert("")
    support.SetModifiers(false, false, false)
    Equal(editBox:GetText(), "")
    page:UndoEditor(); Equal(editBox:GetText(), "cut this")
    Equal(editBox.highlight[1], 0)
    Equal(editBox.highlight[2], #"cut this")
    page:RedoEditor(); Equal(editBox:GetText(), "")
end)

Test("Ctrl+A selection survives its native caret notification", function()

-- Run from the addon root with Lua 5.1: lua Tests/ConsoleHistoryTest.lua
-- Also runs the Find & Replace regression suite using the same native UI mock.
local support = assert(loadfile("Tests/ConsoleSearchTest.lua"))()
local Test, Equal = support.Test, support.Equal
local searchTests = support.GetTestCount()

local function Editor(text)
    local page, editBox = support.Editor(text or "", "")
    page:CloseSearch()
    editBox:SetCursorPosition(#editBox:GetText())
    page:ResetEditorHistory()
    return page, editBox
end

local function Type(editBox, text)
    for character in text:gmatch("[%z\1-\127\194-\244][\128-\191]*") do
        editBox:Fire("OnKeyDown", character:upper())
        editBox:Insert(character)
        editBox:Fire("OnKeyUp", character:upper())
        support.AdvanceTime(0.05)
    end
end

local function Shortcut(editBox, key, shift)
    support.SetModifiers(true, shift, false)
    editBox:Fire("OnKeyDown", key)
    editBox:Fire("OnKeyUp", key)
    support.SetModifiers(false, false, false)
end

local function Paste(editBox, text, split)
    support.SetModifiers(true, false, false)
    editBox:Fire("OnKeyDown", "V")
    if split then
        for character in text:gmatch("[%z\1-\127\194-\244][\128-\191]*") do
            editBox:Insert(character)
        end
    else
        editBox:Insert(text)
    end
    editBox:Fire("OnKeyUp", "V")
    support.SetModifiers(false, false, false)
end

Test("Undo and Redo safely ignore empty history", function()
    local page, editBox = Editor("baseline")
    Shortcut(editBox, "Z"); Shortcut(editBox, "Y"); Shortcut(editBox, "Z", true)
    Equal(editBox:GetText(), "baseline")
    Equal(#page.EditorHistory.States, 1)
    Equal(page.EditorHistory.Index, 1)
end)

Test("continuous ordinary typing is one undoable step", function()
    local page, editBox = Editor()
    Type(editBox, "print('hello')")
    Equal(#page.EditorHistory.States, 2)
    Shortcut(editBox, "Z"); Equal(editBox:GetText(), "")
    Shortcut(editBox, "Y"); Equal(editBox:GetText(), "print('hello')")
    Equal(#page.EditorHistory.States, 2)
end)

Test("Ctrl+Shift+Z redoes the last undone step", function()
    local _, editBox = Editor()
    Type(editBox, "lua")
    Shortcut(editBox, "Z"); Equal(editBox:GetText(), "")
    Shortcut(editBox, "Z", true); Equal(editBox:GetText(), "lua")
end)

Test("a pause creates a new typing step", function()
    local page, editBox = Editor()
    Type(editBox, "one")
    support.AdvanceTime(1.1)
    Type(editBox, "two")
    Equal(#page.EditorHistory.States, 3)
    page:UndoEditor(); Equal(editBox:GetText(), "one")
    page:UndoEditor(); Equal(editBox:GetText(), "")
end)

Test("cursor movement separates typing groups and restores the caret", function()
    local page, editBox = Editor()
    Type(editBox, "ab")
    editBox:Fire("OnKeyDown", "LEFT"); editBox:SetCursorPosition(1)
    Type(editBox, "X")
    Equal(editBox:GetText(), "aXb")
    page:UndoEditor(); Equal(editBox:GetText(), "ab")
    Equal(editBox:GetCursorPosition(), 1)
    page:RedoEditor(); Equal(editBox:GetText(), "aXb")
    Equal(editBox:GetCursorPosition(), 2)
end)

Test("geometry notifications alone do not split typing", function()
    local page, editBox = Editor()
    Type(editBox, "a")
    editBox:Fire("OnCursorChanged")
    Type(editBox, "b")
    Equal(#page.EditorHistory.States, 2)
    page:UndoEditor(); Equal(editBox:GetText(), "")
end)

Test("deletion has a boundary separate from typing", function()
    local page, editBox = Editor()
    Type(editBox, "abc")
    editBox:Fire("OnKeyDown", "BACKSPACE")
    editBox:HighlightText(2, 3); editBox:Insert("")
    Equal(editBox:GetText(), "ab")
    page:UndoEditor(); Equal(editBox:GetText(), "abc")
    Equal(editBox:GetCursorPosition(), 3)
    page:UndoEditor(); Equal(editBox:GetText(), "")
    page:RedoEditor(); page:RedoEditor(); Equal(editBox:GetText(), "ab")
end)

Test("forward Delete restores the document and caret", function()
